// Pre-generates tactical puzzles (the deep searches are too slow to run while you wait).
// Usage: node chess/tools/build-bank.mjs <kind> <level> <count> <seed> <out.json>
// Then: node chess/tools/build-bank.mjs --merge <part.json>... to write chess/bank.js

import { writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { rng } from "../puzzles.js";
import { generateTactic, analysePuzzle, buildLine, theme, toUci, gainBanked } from "../tactics.js";
import { Position } from "../engine.js";
import { evaluate } from "../search.js";

// A "win" line must end with the material actually won (or mate), not cut off mid-fight.
function lineFinishes(fen, line, kind) {
  if (kind !== "win") return true;
  const pos = new Position(fen), base = evaluate(pos);
  for (const m of line) pos.make(m);
  return line.length % 2 === 1 && gainBanked(pos, base);
}

const args = process.argv.slice(2);
if (args[0] === "--merge") {
  const bank = {};
  for (const f of args.slice(1)) {
    const part = JSON.parse(await readFile(f, "utf8"));
    const { fromUci } = await import("../tactics.js");
    const kind = part.id.replace(/\d/, "");
    (bank[part.id] ??= []).push(...part.puzzles.filter(([fen, ucis]) => {
      const pos = new Position(fen), line = [];
      for (const u of ucis.split(" ")) { const m = fromUci(pos, u); line.push(m); pos.make(m); }
      return lineFinishes(fen, line, kind);
    }));
  }
  const out = fileURLToPath(new URL("../bank.js", import.meta.url));
  const body = Object.entries(bank).sort().map(([id, list]) =>
    `  ${id}: [\n${list.map((p) => `    ${JSON.stringify(p)},`).join("\n")}\n  ],`).join("\n");
  await writeFile(out, "// Generated by chess/tools/build-bank.mjs: [fen, main line (UCI), theme, bait move (UCI) or \"\"].\n" +
    "// Every entry passed the same checks the live generator applies.\n\nexport const BANK = {\n" + body + "\n};\n");
  console.log("wrote", out, Object.fromEntries(Object.entries(bank).map(([k, v]) => [k, v.length])));
} else {
  const [kind, level, count, seed, out] = args;
  const random = rng(Number(seed)), puzzles = [], seen = new Set();
  const t = Date.now();
  while (puzzles.length < Number(count)) {
    const p = generateTactic(kind, Number(level), random, 50);
    if (!p || seen.has(p.fen)) continue;
    seen.add(p.fen);
    const a = analysePuzzle(p.fen, kind, Number(level));
    const line = buildLine(p.fen, kind, Number(level), a);
    if (!lineFinishes(p.fen, line, kind)) continue;
    puzzles.push([p.fen, line.map(toUci).join(" "), theme(p.fen, a.key), a.bait ? toUci(a.bait) : ""]);
    await writeFile(out, JSON.stringify({ id: kind + level, puzzles }));
    console.log(`${kind}${level} ${puzzles.length}/${count} ${((Date.now() - t) / 1000).toFixed(0)}s`);
  }
}
